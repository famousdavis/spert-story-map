/**
 * The id the fold gives a moved product it keeps as a copy (v0.56.1, review -03). Derived from the
 * person's uid, the source id and the source's stored text, so a fold that stopped after writing the
 * copy and before removing the source finds the same id when it runs again, and does not make a
 * second copy. A different text (an older tab's later write) gives a different id.
 *
 * The hash is cyrb128 (public domain), 128 bits, laid out as a UUID with version 8 ("custom") and the
 * RFC 9562 variant, so it reads as an id like any other. It is not a security measure.
 */
function cyrb128(text: string): [number, number, number, number] {
  let h1 = 1779033703, h2 = 3144134277, h3 = 1013904242, h4 = 2773480762;
  for (let i = 0; i < text.length; i++) {
    const k = text.charCodeAt(i);
    h1 = h2 ^ Math.imul(h1 ^ k, 597399067);
    h2 = h3 ^ Math.imul(h2 ^ k, 2869860233);
    h3 = h4 ^ Math.imul(h3 ^ k, 951274213);
    h4 = h1 ^ Math.imul(h4 ^ k, 2716044179);
  }
  h1 = Math.imul(h3 ^ (h1 >>> 18), 597399067);
  h2 = Math.imul(h4 ^ (h2 >>> 22), 2869860233);
  h3 = Math.imul(h1 ^ (h3 >>> 17), 951274213);
  h4 = Math.imul(h2 ^ (h4 >>> 19), 2716044179);
  h1 ^= h2 ^ h3 ^ h4;
  h2 ^= h1;
  h3 ^= h1;
  h4 ^= h1;
  return [h1 >>> 0, h2 >>> 0, h3 >>> 0, h4 >>> 0];
}

export function foldCopyId(uid: string, sourceId: string, sourceText: string): string {
  const hex = cyrb128(`${uid}\u0000${sourceId}\u0000${sourceText}`).map(h => h.toString(16).padStart(8, '0')).join('');
  const variant = ((parseInt(hex.charAt(16), 16) & 0x3) | 0x8).toString(16);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-8${hex.slice(13, 16)}-${variant}${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}
